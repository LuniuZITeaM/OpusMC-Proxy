def packet_ids(source, direction):
    block = source.split(direction + '_TEMPLATE =', 1)[1].split('\n    );', 1)[0]
    names = re.findall(r'\.(?:addPacket|withBundlePacket)\(\w+\.' + direction + r'_([A-Z_0-9]+)', block)
    if not names or len(names) != len(set(names)):
        raise ValueError('Empty or duplicate packet registrations: ' + direction)
    return dict(zip(names, range(len(names))))


def generate_ids(source):
    version = json.loads((source / 'version.json').read_text())
    if (version['id'], version['protocol_version']) != ('26.2', 776):
        raise ValueError('Expected vanilla 26.2 protocol 776')
    base = source / 'net/minecraft/network/protocol'
    game = (base / 'game/GameProtocols.java').read_text()
    config = (base / 'configuration/ConfigurationProtocols.java').read_text()
    groups = {name: packet_ids(text, direction) for name, text, direction in (
        ('clientbound', game, 'CLIENTBOUND'), ('serverbound', game, 'SERVERBOUND'),
        ('configClientbound', config, 'CLIENTBOUND'), ('configServerbound', config, 'SERVERBOUND'))}
    assert groups['clientbound']['BUNDLE'] == 0
    lines = ['// Generated by tool/generate_protocol.py from vanilla 26.2 (protocol 776).',
             '// withBundlePacket reserves the first clientbound play wire ID.',
             'const protocolVersion = 776;', '']
    for name, entries in groups.items():
        lines.append(f'const {name} = <String, int>{{')
        lines.extend(f"  '{key}': 0x{value:02x}," for key, value in entries.items())
        lines.extend(['};', ''])
    output = ROOT / 'lib/protocol/ids.dart'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    print('Packet counts:', {key: len(value) for key, value in groups.items()}, flush=True)


