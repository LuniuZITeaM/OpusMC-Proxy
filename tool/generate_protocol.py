"""Generate 26.2 IDs and lossless configuration NBT using local vanilla code.

Python 3, Java/Javac 25; no server launch, EULA, network, or third party Python
packages. --ids-only needs only the decompiled reference sources. Full export
uses an unmodified vanilla jar and cached launcher/Gradle libraries. If none is
available, --download-vanilla verifies 26.2 in Mojang's official manifest and
SHA-1 checks the client jar downloaded into the system temporary directory.
"""
