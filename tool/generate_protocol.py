def export_registries(jar, minecraft, gradle):
    with zipfile.ZipFile(jar) as archive:
        version = json.loads(archive.read('version.json'))
        if (version['id'], version['protocol_version']) != ('26.2', 776):
            raise ValueError('Jar is not vanilla 26.2 protocol 776')
        if b'FabricRegistry' in archive.read('net/minecraft/core/Registry.class'):
            raise ValueError('Fabric-injected jar cannot run standalone; use an unmodified vanilla jar')
    launch = json.loads((minecraft / 'versions/26.2/26.2.json').read_text())
    libraries = []
    for lib in launch['libraries']:
        artifact = lib.get('downloads', {}).get('artifact')
        if artifact is None or 'natives-' in artifact['path'] or '-native-' in artifact['path'] or lib['name'].startswith('org.lwjgl:'):
            continue
        group, name, version, *classifier = lib['name'].split(':')
        path = minecraft / 'libraries' / artifact['path']
        if not path.exists():
            path = next((gradle / 'caches/modules-2/files-2.1' / group / name / version).glob('*/' + Path(artifact['path']).name), path)
        if not path.exists() and (group == 'io.netty' or (group, name) == ('com.mojang', 'authlib')):
            alternatives = sorted((gradle / 'caches/modules-2/files-2.1' / group / name).glob('*/*/*.jar'))
            alternatives = [p for p in alternatives if not p.name.endswith(('-sources.jar', '-javadoc.jar'))]
            if alternatives:
                path = alternatives[-1]
                print('Using cached headless dependency:', path, flush=True)
        libraries.append(path)
    missing = [str(p) for p in libraries if not p.exists()]
    if missing:
        raise FileNotFoundError('Missing matching launcher libraries:\n' + '\n'.join(missing))
    classpath = os.pathsep.join(map(str, [jar, *libraries]))
    assets = ROOT / 'assets'
    assets.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='opusmc-registry-') as temp:
        temp = Path(temp)
        helper = temp / 'ExportRegistries.java'
        helper.write_text(JAVA_EXPORT, encoding='utf-8')
        subprocess.run(['javac', '-cp', classpath, str(helper)], check=True, cwd=temp)
        # Run in scratch space so Java logging creates no files in the project.
        subprocess.run(['java', '-Xmx2G', '-cp', os.pathsep.join([str(temp), classpath]),
                        'ExportRegistries', str(temp / 'packets.json'), str(temp / 'registries.json')],
                       check=True, cwd=temp)
        for source, target in [('packets.json', 'registries.json')]:
            (assets / target).write_bytes((temp / source).read_bytes())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=DEFAULT_SOURCE)
    parser.add_argument('--ids-only', action='store_true')
    parser.add_argument('--jar', type=Path, help='Unobfuscated vanilla or Loom merged 26.2 jar')
    parser.add_argument('--download-vanilla', action='store_true', help='Permit official manifest lookup and SHA-1 verified client download')
    parser.add_argument('--minecraft', type=Path, default=Path(os.environ.get('APPDATA', str(Path.home()))) / '.minecraft')
    parser.add_argument('--gradle', type=Path, default=Path(os.environ.get('GRADLE_USER_HOME', 'D:/Dev/.gradle')))
    args = parser.parse_args()
    generate_ids(args.source)
    if not args.ids_only:
        jar = args.jar
        if jar is None:
            cache = args.source.parents[2] / '.gradle/loom-cache/minecraftMaven/net/minecraft'
            candidates = [args.gradle / 'caches/fabric-loom/26.2/minecraft-client.jar',
                          args.minecraft / 'versions/26.2/26.2.jar',
                          Path(tempfile.gettempdir()) / 'opusmc-vanilla-26.2.jar',
                          *cache.glob('*/26.2/*.jar')]
            for candidate in candidates:
                if not candidate.exists():
                    continue
                with zipfile.ZipFile(candidate) as archive:
                    if b'FabricRegistry' not in archive.read('net/minecraft/core/Registry.class'):
                        jar = candidate
                        break
        if jar is None and args.download_vanilla:
            def fetch_json(url):
                with urllib.request.urlopen(url, timeout=60) as response:
                    return json.load(response)
            manifest = fetch_json('https://piston-meta.mojang.com/mc/game/version_manifest_v2.json')
            entry = next(v for v in manifest['versions'] if v['id'] == '26.2' and v['type'] == 'release')
            metadata = fetch_json(entry['url'])
            artifact = metadata['downloads']['client']
            jar = Path(tempfile.gettempdir()) / 'opusmc-vanilla-26.2.jar'
            urllib.request.urlretrieve(artifact['url'], jar)
            if hashlib.sha1(jar.read_bytes()).hexdigest() != artifact['sha1']:
                raise ValueError('Official client jar SHA-1 mismatch')
        if jar is None:
            parser.error('No unmodified local jar found; provide --jar, --download-vanilla, or --ids-only')
        export_registries(jar.resolve(), args.minecraft, args.gradle)


if __name__ == '__main__':
    main()
